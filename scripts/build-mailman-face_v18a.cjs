// Builds src/lib/mailman-face.generated.ts: the mailman split into a still part
// (head, hair, collar, moustache, cap) and the pieces that move (eyes, brows, mouth),
// so his expression can change smoothly. Run: npm run artwork:face
const fs = require('node:fs');
const path = require('node:path');
const { renderAvatar, rigPieces } = require('../artwork/avatars/kit.cjs');

const layers = renderAvatar('mailman', { layers: true, id: 'mf' });
const { openEyes, eyesClosed } = rigPieces();
const parts = openEyes.match(/<path[^>]*\/>|<circle[^>]*\/>/g);
if (!parts || parts.length !== 6) throw new Error(`Expected 6 eye parts, found ${parts && parts.length}`);
const [whiteL, pupilL, glintL, whiteR, pupilR, glintR] = parts.map(p => p.replace(/\sid="[^"]*"/g, ''));
const arcs = (eyesClosed.match(/ d="([^"]+)"/) || [])[1];
if (!arcs) throw new Error('Closed-eye arcs not found');

const out = {
  viewBox: layers.viewBox,
  ink: layers.ink,
  defs: layers.defs,
  pre: layers.pre,
  post: layers.post,
  whiteL, whiteR,
  pupilL: pupilL + glintL,
  pupilR: pupilR + glintR,
  arcs,
};
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n');
fs.writeFileSync(
  path.resolve(__dirname, '../src/lib/mailman-face.generated.ts'),
  `// Generated by scripts/build-mailman-face.cjs. Do not edit by hand.\nexport const mailmanFace = {\n${body}\n} as const;\n`,
);
console.log('Wrote src/lib/mailman-face.generated.ts');
