// Builds src/lib/tiger-scene.generated.ts for the Panic Button program page (the tiger that becomes a kitten).
// The art (roaring tiger head, glossy red button, kitten, puff, rings) was drawn by the storyboard script
// sw-characters/.../cards-anim/panic-tiger/build.cjs; this script runs its drawing functions and writes the pieces as SVG text, each in a group with an id.
// Run: node scripts/build-tiger-scene.cjs
const fs = require("fs");
const dir = "/Users/mayankav/Documents/speechworks-2/sw-characters/native/prototype/shots/s22/site-avatars/cards-anim/panic-tiger";
const src = fs.readFileSync(dir + "/build.cjs", "utf8");
const a = src.indexOf("const K=");
const b = src.indexOf("// ---------- his face in each frame");
if (a < 0 || b < 0) throw new Error("storyboard script changed");
const art = new Function("fs", "dir", "const BLOB='';" + src.slice(a, b).replace(/const BLOB=[^\n]*\n/, "") + `
const TG={x:-298,y:-34,s:0.42}, KX=298, KY=350;
return { shadow, tiger, kitten, button, sparkle, popBurst, ring, poof, breath, drop, BX, BY, BK, TG, TX, TY, KX, KY };`)(fs, dir);
const { shadow, tiger, kitten, button, sparkle, popBurst, ring, poof, breath, drop, BX, BY, BK, TG, KX, KY } = art;
const g = (id, inner, extra = "") => `<g id="${id}" ${extra}>${inner}</g>`;
// The panic button, copied from the founder's picture: a stone-grey box with a recessed round red button and a red arrow under it (thick dark outline, a side face and a top face).
// Layout is kept clean on purpose: tiger / kitten on the left, him in the middle, the button box on the right.
const INK = "#242329", J = 'stroke-linejoin="round" stroke-linecap="round"';
const BCX = 298, BCY = 274, BS = 1.3;   // base centre of the box, scale
const box = (pressed) => {
  const o = pressed ? 0 : 3.4;   // how far the red button stands out of its hole
  return `<polygon points="23,-66 37,-73 39,-8 25,1" fill="#A89E8E" stroke="${INK}" stroke-width="4" ${J}/>`
    + `<polygon points="-25,-61 -9,-71 37,-73 23,-66" fill="#E6DECF" stroke="${INK}" stroke-width="3.6" ${J}/>`
    + `<polygon points="-25,-61 23,-66 25,1 -23,-2" fill="#D6CDBD" stroke="${INK}" stroke-width="4.6" ${J}/>`
    + `<path d="M-19 -55L-17.5 -9" stroke="#fff" stroke-opacity=".55" stroke-width="3" ${J}/>`
    + `<ellipse cx="0" cy="-37" rx="17.5" ry="19.5" fill="#B3A998" stroke="${INK}" stroke-width="3.2" ${J}/>`
    + `<ellipse cx="${1 + o * 0.5}" cy="-37" rx="13" ry="15" fill="#B3231B" stroke="${INK}" stroke-width="2.8" ${J}/>`
    + `<ellipse cx="${-0.5 + o}" cy="${-38.5}" rx="12.5" ry="14.5" fill="${pressed ? "#C9271D" : "#EE3B2E"}" stroke="${INK}" stroke-width="2.8" ${J}/>`
    + (pressed ? "" : `<path d="M-6 -46Q-3 -52 3 -52" stroke="#fff" stroke-opacity=".75" stroke-width="2.6" ${J} fill="none"/>`)
    + `<path d="M-1 -27L-10.5 -16L-4.5 -16L-4 -6L4.5 -6L4.5 -16L10.5 -16Z" fill="#EE3B2E" stroke="${INK}" stroke-width="3" ${J}/>`;
};
const at = (inner) => `<g transform="translate(${BCX} ${BCY}) scale(${BS})">${inner}</g>`;
const RC = { x: BCX, y: BCY - 50 * BS };
const ringSvg = `<circle cx="${RC.x}" cy="${RC.y}" r="40" fill="none" stroke="#fff" stroke-opacity=".9" stroke-width="5"/><circle cx="${RC.x}" cy="${RC.y}" r="64" fill="none" stroke="#fff" stroke-opacity=".5" stroke-width="4"/>`;
const KPOS = { x: -62, y: 346 };
const kittenSvg = shadow(KPOS.x + 4, KPOS.y + 1, 52) + kitten({ x: KPOS.x, y: KPOS.y, s: 1.2 }).replace(/#F08A2C/gi, "#F5921E").replace(/#D4621A/gi, "#1F1D1E");
const under = g("tg-ring", ringSvg, 'opacity="0"');
const over =
  g("tg-big", shadow(-84, 346, 118) + tiger(TG), 'opacity="0"') +
  g("tg-drop", drop, 'opacity="0"') +
  g("tg-small", shadow(-92, 346, 64) + tiger({ x: -200, y: 155, s: 0.21, mode: "oh" }), 'opacity="0"') +
  g("tg-poof", poof, 'opacity="0"') +
  g("tg-btn0", at(box(false)), 'opacity="0"') +
  g("tg-btn1", at(box(true)), 'opacity="0"') +
  g("tg-kit", kittenSvg, 'opacity="0"') +
  g("tg-breath", breath, 'opacity="0"') +
  g("tg-s1", sparkle(-4, 196, 9, "#fff"), 'opacity="0"') + g("tg-s2", sparkle(-190, 170, 10), 'opacity="0"') + g("tg-s3", sparkle(6, 318, 8), 'opacity="0"');
fs.writeFileSync("src/lib/tiger-scene.generated.ts", `// GENERATED by scripts/build-tiger-scene.cjs. Do not edit by hand.\nexport const tigerUnder = ${JSON.stringify(under)};\nexport const tigerOver = ${JSON.stringify(over)};\n`);
console.log("ok", under.length + over.length);
