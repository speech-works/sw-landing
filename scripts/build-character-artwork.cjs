const fs = require('node:fs');
const path = require('node:path');
const { renderCharacter } = require('../artwork/avatars/character-rig.cjs');
const { renderAvatar } = require('../artwork/avatars/kit.cjs');
const { renderInterviewCandidate } = require('../artwork/avatars/interview-candidate.cjs');
const artwork = Object.fromEntries(['curly', 'communicator', 'beanie', 'hijab'].map(name =>
  [name, renderCharacter(name, { id: 'character-id' })]
));
artwork.interview = renderInterviewCandidate();
// Keep the mirror's effort expression and facial landmarks fixed. Only blink.
artwork.mirror = renderAvatar('bob', { id: 'character-id', mood: 'effort', headwear: 'none' })
  .replace(/<g id="[^"]+-eyes">/, '<g class="rig-eyes">')
  .replace('role="img"', 'aria-hidden="true" focusable="false"');
fs.writeFileSync(path.join(__dirname, '../src/lib/character-artwork.generated.ts'),
  '// Generated by scripts/build-character-artwork.cjs from the approved avatar kit.\n' +
  'export const characterArtwork = ' + JSON.stringify(artwork, null, 2) + ' as const;\n');
console.log('Built gentle character artwork');
